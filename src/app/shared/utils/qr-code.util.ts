/** Largeurs successives barre / espace (en modules) d'un code-barres Code 128, marges comprises. */
export function encodeCode128(text: string): number[] {
  const numeric = /^(\d\d)+$/.test(text);
  if (!numeric && !/^[\x20-\x7e]*$/.test(text)) throw new Error('Code 128 B : caractères ASCII imprimables uniquement');
  const codes = numeric ? [105, ...(text.match(/\d\d/g) ?? []).map(Number)] : [104, ...Array.from(text, (c) => c.charCodeAt(0) - 32)];
  const check = codes.reduce((s, c, i) => s + c * (i || 1), 0) % 103;
  return [...codes, check, 106].flatMap((c) => C128[c].split('').map(Number));
}
