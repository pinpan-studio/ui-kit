/**
 * Encodeur QR Code (ISO/IEC 18004) autonome, mode octet (UTF-8), versions 1–40, niveaux L/M/Q/H.
 * Inspiré de l'implémentation de référence de Project Nayuki (licence MIT).
 * Renvoie une matrice de modules (`true` = noir).
 */
export type QrEcc = 'L' | 'M' | 'Q' | 'H';

const ECC_ORD: Record<QrEcc, number> = { L: 0, M: 1, Q: 2, H: 3 };
const FORMAT_BITS: Record<QrEcc, number> = { L: 1, M: 0, Q: 3, H: 2 };

